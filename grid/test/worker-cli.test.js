// 命令行版（租来的 Linux 显卡）：加入、开始算、领任务做完、Ctrl+C 停
"use strict";
process.removeAllListeners("warning"); process.on("warning", () => {});
const assert = require("assert");
const fs = require("fs"), os = require("os"), path = require("path");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "lg-cli-"));
process.env.LG_ADMIN_HOME = path.join(tmp, "admin");
process.env.LG_WORKER_HOME = path.join(tmp, "worker");
const Server = require("../server");
const Tools = require("../tools/grid");
const W = require("../tools/worker");
const PY = process.env.PYTHON || "python3";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const app = Server.create({ data: path.join(tmp, "server"), leaseMs: 5000, noTick: true });
  const port = await app.listen(0, "127.0.0.1");
  const url = `http://127.0.0.1:${port}`;
  const admin = await Tools.login(url, app.core.adminToken());
  const rf = path.join(tmp, "big_train.py");
  fs.writeFileSync(rf, 'import lg\nt = lg.task()\nlg.log("在租来的卡上算")\nlg.done(ok=1, i=t["input"]["i"])\n');
  const rid = await Tools.publish(admin, rf, "big_train");
  const job = (await Tools.api(admin, "/api/admin/job", { name: "要大显卡的活", kind: "map", recipe: rid, params: { count: 2 }, req: { vram: 20 } })).id;
  const inv = await Tools.api(admin, "/api/admin/invite", { maxUses: 1, server: url });
  const logs = [];
  const log0 = console.log; console.log = (...a) => logs.push(a.join(" "));
  await W.join([inv.link, "租的4090"]);
  assert.ok(fs.existsSync(path.join(tmp, "worker", "worker.json")));
  const ag = await W.run(["--python", PY, "--work", path.join(tmp, "work")], { noExit: true, probe: { items: [{ name: "显卡", value: "RTX 4090 · 24G" }], caps: { gpu: "RTX 4090", vram: 24, ram: 64, os: "linux" } }, agentOpt: { tickMs: 100, hbMs: 300, leaseEveryMs: 100, renewMs: 300 } });
  for (let i = 0; i < 300 && app.core.jobDetail(job).state !== "done"; i++) await sleep(100);
  await ag.stop();
  console.log = log0;
  assert.equal(app.core.jobDetail(job).state, "done", "24G 的租卡把要大显卡的活做完了");
  assert.ok(logs.some((l) => /领到任务/.test(l)) && logs.some((l) => /在租来的卡上算/.test(l)));
  console.log("✓ 命令行版：加入（邀请链接）、按显卡领活、做完、停止");
  app.close();
  fs.rmSync(tmp, { recursive: true, force: true });
  console.log("命令行版（租卡）：全部通过");
  process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
