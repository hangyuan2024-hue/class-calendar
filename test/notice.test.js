// 6.8 正式通知、带链接的在线表格、分好几行的通知：一次整理对
const assert = require("assert");
const P = require("../parse.js");
const ok = (m) => console.log("✓ " + m);
const one = (t, pub) => { const r = P.parse(t, pub); return { r, x: r.items[0] || {} }; };

// 用户原话：金山文档在线表格 + 截止时间单独一行 + 「上周五」「10.16」干扰
const wps = "提醒🔔：根据上周五工作会议要求，关于期中教学检查工作，请各位老师完成所带班级同学的意见征集并填写下方在线电子表格：【金山文档 | WPS云文档】 汇总版：新生学院2026-2027学年第一学期期中教学检查学生意见10.16\nhttps://www.kdocs.cn/l/cbTBH9IemqeG\n截止时间为10月19日早10点。";
for (const t of [wps, wps.replace(/\n/g, " "), "王老师 10:21\n" + wps + "\n李华 10:22\n收到"]) {
  const { r, x } = one(t, "2026-10-17");
  assert.strictEqual(r.items.length, 1, "一条通知只整理出一件事");
  assert.strictEqual(r.unsure.length, 0, "链接那一行不是单独一条");
  assert.strictEqual(x.msg_type, "通知");
  assert.strictEqual(x.subject, "期中教学检查：填写在线电子表格");
  assert.strictEqual(x.event_time, "2026-10-19 10:00", "截止时间是 10月19日 10:00，不是上周五、也不是表格名里的 10.16");
  assert.strictEqual(x.prepare, "", "「所带班级」不是要带的东西");
  assert.ok(x.summary.includes("https://www.kdocs.cn/l/cbTBH9IemqeG"), "链接原样留在内容里");
  assert.ok(/^要点：期中教学检查/.test(x.summary), "长通知第一句先说要点");
  assert.deepStrictEqual(P.digest(r.items, "2026-10-17").lines, ["后天 10:00前：期中教学检查：填写在线电子表格"]);
}
ok("金山文档在线表格通知：标题、截止时间、链接都对，干扰日期不当真");

